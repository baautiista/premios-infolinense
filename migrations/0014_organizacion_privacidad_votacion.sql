## Una papeleta por participante

Las votaciones no requieren crear una cuenta ni facilitar nombre, correo electrónico o número de teléfono.

Para reducir la participación duplicada, la plataforma utiliza identificadores técnicos y mecanismos de control que permiten detectar posibles intentos de emitir varias papeletas.

El objetivo es que cada persona participe una sola vez. No obstante, al tratarse de una votación abierta y sin identificación personal, no es posible garantizar técnicamente que nadie vote utilizando dispositivos o conexiones diferentes.

## Protección frente a votos fraudulentos

### Verificación antibots

El sistema utiliza Cloudflare Turnstile para dificultar la emisión automatizada de papeletas.

### Controles técnicos

Se utilizan identificadores del navegador y controles de conexión para detectar posibles duplicidades o comportamientos anómalos.

### Validación en el servidor

Todas las papeletas se comprueban antes de registrarse. Solo se admiten selecciones correspondientes a candidaturas y categorías habilitadas.

### Revisión de irregularidades

Las papeletas que presenten señales de posible fraude podrán quedar sometidas a una revisión específica.

Compartir una misma conexión a Internet no constituye por sí solo una prueba de fraude. Varias personas pueden votar legítimamente desde una misma vivienda, centro educativo o lugar de trabajo.

## Revisión y anulación de papeletas

La organización podrá revisar los registros técnicos cuando se detecten posibles irregularidades.

La anulación de una papeleta requerirá una justificación y quedará registrada internamente, incluyendo la causa y la persona responsable de la decisión.

No se anularán votos por la identidad de la candidatura elegida ni por el resultado que pueda producir una votación legítima.

## Comprobante de participación

Tras registrar una papeleta, el sistema facilitará un código de comprobante.

Este código servirá para consultar el estado del registro de la papeleta, pero no permitirá emitir nuevos votos ni modificar las selecciones realizadas.

El comprobante no representa una acreditación pública de la identidad del participante.

## Privacidad

No se solicita información identificativa directa para participar.

El sistema puede tratar identificadores técnicos seudonimizados con la finalidad de proteger la votación frente a abusos. Estos identificadores y su tratamiento se explican en la [Política de privacidad](/privacidad).

Los datos de control no se utilizarán para crear perfiles comerciales de los votantes.

## Resultados

Los resultados parciales permanecerán ocultos durante el periodo de votación.

Al finalizar el plazo, la organización revisará las papeletas y determinará los resultados a partir de los votos considerados válidos.

Los ganadores se anunciarán en la web oficial de los Premios InfoLinense, junto con la información del escrutinio.

