## 5. Base jurídica

InfoLinense trata los datos personales estrictamente necesarios para organizar los Premios InfoLinense 2026, gestionar la votación popular, garantizar la seguridad de la plataforma y difundir las candidaturas y los resultados del certamen.

De conformidad con el artículo 6 del Reglamento General de Protección de Datos (RGPD), los tratamientos se fundamentan en las siguientes bases jurídicas:

### 1. Gestión de las votaciones y prevención del fraude

El interés legítimo de InfoLinense (artículo 6.1.f del RGPD) en organizar una votación participativa, transparente y segura, preservar la integridad de los resultados y prevenir la emisión de papeletas duplicadas, automatizadas o fraudulentas.

Con estas finalidades podrán tratarse identificadores técnicos seudonimizados, información relacionada con las papeletas y registros de seguridad, siempre que sean necesarios y proporcionados.

La aplicación de esta base jurídica requiere una ponderación documentada entre los intereses de la organización y los derechos y libertades de las personas participantes.

### 2. Publicación de fotografías y datos de las candidaturas

La publicación de fotografías, presentaciones personales y otros datos facilitados por las personas nominadas se fundamentará, cuando corresponda, en su consentimiento (artículo 6.1.a del RGPD), solicitado previamente para la difusión del certamen.

Las personas interesadas podrán retirar dicho consentimiento en cualquier momento, sin que ello afecte a la licitud del tratamiento realizado con anterioridad.

Cuando InfoLinense publique contenidos de carácter informativo en el ejercicio de su actividad periodística, se aplicará la base jurídica y el régimen legal que correspondan a esa finalidad.

### 3. Atención de consultas y solicitudes

Las comunicaciones recibidas a través de los canales de contacto se tratarán con la finalidad de atender consultas, gestionar incidencias y responder a las solicitudes relacionadas con los premios, sobre la base del interés legítimo de la organización, cuando resulte aplicable.

### 4. Cumplimiento de obligaciones legales

Cuando sea necesario conservar o comunicar determinada información para cumplir una obligación legal, el tratamiento se fundamentará en el artículo 6.1.c del RGPD.

En todos los casos, InfoLinense aplicará los principios de minimización de datos, limitación de la finalidad, confidencialidad y conservación durante el tiempo estrictamente necesario.

El uso de cookies, almacenamiento local y otras tecnologías de identificación del dispositivo se ajustará, además, a la normativa específica aplicable, solicitándose el consentimiento cuando legalmente resulte exigible.

Los datos personales tratados para garantizar la seguridad de las votaciones no se utilizarán para publicidad personalizada ni se facilitarán a los patrocinadores del certamen.

