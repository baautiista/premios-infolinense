Los Premios InfoLinense nacen con el propósito de reconocer el talento, el esfuerzo, la dedicación y las iniciativas que contribuyen al desarrollo y a la vida social, cultural y económica de La Línea de la Concepción.

Estas bases regulan las candidaturas, el sistema de votación, la elección de las personas y entidades ganadoras y las condiciones generales de participación en su primera edición.

## 1. Objeto y finalidad

Los Premios InfoLinense son unos reconocimientos promovidos por el periódico digital InfoLinense para distinguir a personas, profesionales, empresas, comercios, centros educativos, asociaciones y colectivos que hayan destacado por su trayectoria, actividad o aportaciones a La Línea de la Concepción.

La primera edición se celebra en 2026 y pretende convertirse en una iniciativa anual de reconocimiento al talento y al compromiso con la ciudad.

Los premios tienen carácter de reconocimiento público y no contemplan una dotación económica.

## 2. Entidad organizadora

Los Premios InfoLinense 2026 están organizados por InfoLinense, medio de comunicación digital dedicado a la actualidad de La Línea de la Concepción y el Campo de Gibraltar.

La organización es responsable de la coordinación del certamen, la selección de candidaturas y la gestión de las votaciones.

## 3. Categorías oficiales

La edición 2026 comprende once categorías sometidas a votación popular:

- **Mérito Deportivo**: reconocimiento a deportistas destacados por sus resultados y trayectoria.
- **Talento Emprendedor**: reconocimiento a iniciativas empresariales y proyectos de emprendimiento.
- **Comercio a Pie de Calle**: reconocimiento a establecimientos y profesionales del comercio local.
- **Arte con Firma**: reconocimiento al talento artístico y creativo.
- **Creación en Red**: reconocimiento a creadores de contenido y profesionales de la comunicación digital.
- **Vocación Educativa**: reconocimiento a docentes, centros y proyectos educativos.
- **Vida Asociativa**: reconocimiento a asociaciones y colectivos por su contribución a la ciudad.
- **Acción de Barrio**: reconocimiento a iniciativas que mejoran la vida de los barrios linenses.
- **Carnaval Linense**: reconocimiento a personas, agrupaciones y proyectos vinculados al Carnaval.
- **Vocación Cofrade**: reconocimiento a personas por su trayectoria y dedicación a la Semana Santa.
- **Impulso Cofrade**: reconocimiento a proyectos e iniciativas que conservan, enriquecen o divulgan la cultura cofrade.

Las categorías Vocación Cofrade e Impulso Cofrade son independientes, cuentan con candidaturas y votaciones distintas y tendrán cada una su propio ganador.

## 4. Selección de candidaturas

Las candidaturas se han elaborado a partir de las propuestas recibidas de los vecinos y de la labor de selección editorial realizada por InfoLinense.

Para su selección se han tenido en cuenta la vinculación con La Línea de la Concepción, la trayectoria de las personas o entidades propuestas, sus actividades y los méritos destacados durante 2026.

La categoría Acción de Barrio cuenta con cuatro candidaturas propuestas por la Federación Local de Asociaciones de Vecinos Inmaculada (FLAVI).

La presentación oficial de las candidaturas tendrá lugar el 25 de noviembre de 2026, a través de los canales de InfoLinense y de la web oficial del certamen.

Las candidaturas tienen carácter de nominación. Su inclusión no supone la concesión de un premio ni constituye una clasificación de méritos entre los participantes.

## 5. Participación y votación popular

Los ganadores de las once categorías ordinarias se decidirán mediante votación popular en:

[premios.infolinense.com](https://premios.infolinense.com)

La participación será gratuita.

Cada participante deberá emitir una única papeleta, en la que podrá seleccionar una candidatura por cada categoría que desee votar. No será obligatorio votar en todas las categorías.

Una vez confirmada y registrada, la papeleta no podrá modificarse.

La organización aplicará medidas técnicas para prevenir votaciones automatizadas, duplicadas o fraudulentas. Estas medidas no permiten garantizar de manera absoluta la identidad individual de cada votante.

Las fechas y horas de apertura y cierre se anunciarán en la web oficial, utilizando el horario peninsular español (Europe/Madrid).

Durante el periodo de votación no se publicarán resultados parciales.

## 6. Determinación de ganadores

En cada categoría resultará ganadora la candidatura que obtenga el mayor número de votos válidos una vez finalizado el periodo de votación y completada la revisión de posibles irregularidades.

Únicamente se tendrán en cuenta las papeletas admitidas conforme a las presentes bases.

Cada categoría contará con un reconocimiento independiente. La candidatura conjunta de Ernesto Frigolet y Pepe Guzmán, dentro de Vocación Cofrade, se considerará una única candidatura a efectos de votación.

## 7. Desempates

En caso de empate a votos válidos entre dos o más candidaturas de una misma categoría, su concesión corresponderá exclusivamente a la redacción de InfoLinense y no estará sometida a votación popular.

## 8. Prevención del fraude y revisión de votos

La organización establecerá controles destinados a detectar y dificultar la emisión de votos automatizados o repetidos.

Estos controles podrán incluir verificaciones antibots, identificadores técnicos seudonimizados, limitaciones de solicitudes y mecanismos de detección de comportamientos anómalos.

Las papeletas sospechosas podrán quedar sometidas a revisión.

La anulación de cualquier papeleta deberá responder a una causa justificada y quedar registrada internamente, indicando el motivo y la persona responsable de la decisión.

La organización no podrá modificar arbitrariamente los votos válidos ni alterar los resultados por motivos comerciales, publicitarios o ajenos al procedimiento establecido.

## 9. Publicación de resultados y entrega de premios

Los resultados oficiales se publicarán en la web de los Premios InfoLinense y en los canales de comunicación del medio.

No se celebrará una gala presencial. El anuncio de los ganadores se realizará mediante una presentación digital.

Cada candidatura ganadora recibirá un trofeo físico como recuerdo y reconocimiento de su distinción.

La organización se pondrá en contacto con las personas o entidades premiadas para acordar la entrega de los galardones.

La fecha de publicación de resultados se comunicará oficialmente a través de la web.

## 10. Patrocinios e independencia

Los Premios InfoLinense podrán contar con empresas y entidades colaboradoras que contribuyan a su organización.

La participación de un patrocinador no le otorgará capacidad de decisión sobre las candidaturas, la votación, la revisión de papeletas o la elección de los ganadores.

Las colaboraciones comerciales deberán identificarse de manera transparente.

## 11. Protección de datos y derechos de imagen

La participación en la votación estará sujeta a la Política de privacidad publicada en esta web.

Las fotografías, nombres y presentaciones de las candidaturas se utilizarán para la difusión del certamen, de acuerdo con las autorizaciones y demás condiciones que correspondan.

La organización procurará que la información relativa a los méritos y trayectorias de los nominados sea correcta y permitirá solicitar la rectificación de datos inexactos.

## 12. Aceptación de las bases

La emisión de una papeleta implica el conocimiento y la aceptación de las presentes bases.

La organización podrá introducir correcciones justificadas por errores materiales, incidencias técnicas o necesidades legales, siempre que se comuniquen públicamente y no alteren de forma arbitraria las condiciones de la votación.

Cualquier cuestión no prevista expresamente se resolverá respetando los principios de transparencia, igualdad de trato y buena fe.

